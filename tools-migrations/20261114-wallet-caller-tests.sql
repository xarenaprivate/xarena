BEGIN;
DO $$DECLARE me uuid;admin_user uuid;logo public.squad_logos;reward public.rewards_catalog;r jsonb;v_id bigint;before_n bigint;BEGIN
SELECT user_id INTO me FROM public.points_ledger ORDER BY id LIMIT 1;
SELECT user_id INTO admin_user FROM public.admins LIMIT 1;
IF admin_user IS NULL THEN RAISE EXCEPTION 'No testable admin role';END IF;
PERFORM set_config('request.jwt.claim.sub',me::text,true);
INSERT INTO public.points_ledger(user_id,delta,kind)VALUES(me,10,'wallet_fixture');
SELECT * INTO logo FROM public.squad_logos WHERE active LIMIT 1;
IF logo.id IS NULL THEN RAISE EXCEPTION 'No logo fixture template';END IF;
logo.id:=gen_random_uuid();logo.title:='Wallet rollback-only fixture';logo.cost_ap:=1;
INSERT INTO public.squad_logos SELECT(logo).*;
SELECT count(*)INTO before_n FROM public.points_ledger;
r:=public.buy_squad_logo(logo.id);IF r->>'ok'<>'true'THEN RAISE EXCEPTION 'Logo buy failed% ',r;END IF;
r:=public.buy_squad_logo(logo.id);IF r->>'already'<>'true'THEN RAISE EXCEPTION 'Repeat logo buy not idempotent% ',r;END IF;
IF(SELECT count(*)FROM public.points_ledger)<>before_n+1 THEN RAISE EXCEPTION 'Duplicate logo debit';END IF;
SELECT * INTO reward FROM public.rewards_catalog WHERE active LIMIT 1;
IF reward.id IS NULL THEN reward.active:=true;reward.sort:=0;reward.created_at:=clock_timestamp();reward.kind:='cosmetic';END IF;
SELECT coalesce(max(id),0)+100000 INTO reward.id FROM public.rewards_catalog;reward.title:='Wallet rollback-only fixture';reward.cost:=1;
INSERT INTO public.rewards_catalog OVERRIDING SYSTEM VALUE SELECT(reward).*;
r:=public.redeem_reward(reward.id);IF r->>'ok'<>'true'THEN RAISE EXCEPTION 'Redemption failed% ',r;END IF;
r:=public.redeem_reward(reward.id);IF r->>'ok'<>'false'THEN RAISE EXCEPTION 'Duplicate redemption accepted';END IF;
SELECT id INTO v_id FROM public.reward_redemptions WHERE user_id=me AND item_id=reward.id AND status='pending';
PERFORM set_config('request.jwt.claim.sub',admin_user::text,true);
r:=public.admin_review_redemption(v_id,'rejected','rollback-only test');IF r->>'ok'<>'true'THEN RAISE EXCEPTION 'Refund failed% ',r;END IF;
r:=public.admin_review_redemption(v_id,'rejected','rollback-only test');IF r->>'ok'<>'false'THEN RAISE EXCEPTION 'Duplicate refund accepted';END IF;
IF(SELECT count(*)FROM public.xr_wallet_allocations WHERE refund_of IN(SELECT id FROM public.points_ledger WHERE user_id=me AND meta->>'redemption'=v_id::text))<>1 THEN RAISE EXCEPTION 'Refund source missing';END IF;
END $$;
SELECT 'PASS caller idempotency: logo purchase, redemption pending guard, admin review/refund source' AS test_result;
ROLLBACK;
