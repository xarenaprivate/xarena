 ASSERT NOT EXISTS(SELECT 1 FROM jsonb_array_elements(j->'players')x,jsonb_object_keys(x)k WHERE k NOT IN('id','username','ign','avatar_url','presence')),'Only approved fields';
 UPDATE public.xr_sf_presence SET state='in_match' WHERE user_id=b;
