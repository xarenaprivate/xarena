 INSERT INTO public.xr_sf_presence(user_id,state,reported_at,expires_at)VALUES(b,'online',clock_timestamp(),clock_timestamp()+interval '2 minutes')ON CONFLICT(user_id)DO UPDATE SET state=excluded.state,reported_at=excluded.reported_at,expires_at=excluded.expires_at;
