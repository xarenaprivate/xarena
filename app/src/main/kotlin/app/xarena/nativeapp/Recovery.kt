import java.net.URL

private suspend fun recoveryRequest(body: JSONObject, enroll: Boolean): JSONObject = withContext(Dispatchers.IO) {
    val conn = URL(Api.BASE + "/functions/v1/player-recovery").openConnection() as HttpURLConnection
    try {
        conn.requestMethod = "POST"; conn.connectTimeout = 10000; conn.readTimeout = 25000; conn.doOutput = true
        conn.setRequestProperty("apikey", Api.KEY); conn.setRequestProperty("Content-Type", "application/json")
        if (enroll) conn.setRequestProperty("Authorization", "Bearer " + (Api.access ?: error("Not logged in.")))
        conn.outputStream.use { it.write(body.toString().toByteArray(Charsets.UTF_8)) }
        val code = conn.responseCode
        val raw = (if (code in 200..299) conn.inputStream else conn.errorStream)?.bufferedReader()?.use { it.readText() } ?: "{}"
        val r = JSONObject(raw)
        check(code in 200..299 && r.optBoolean("ok")) { r.optString("error", "Recovery request failed. Do not retry automatically.") }
        r
    } finally { conn.disconnect() }
}

@Composable
fun RecoveryDialog(enroll: Boolean, onClose: () -> Unit) {
    val context = LocalContext.current
    DisposableEffect(context) {
        val window = (context as? ComponentActivity)?.window
        val alreadySecure = window?.attributes?.flags?.and(WindowManager.LayoutParams.FLAG_SECURE) != 0
        window?.addFlags(WindowManager.LayoutParams.FLAG_SECURE)
        onDispose { if (!alreadySecure) window?.clearFlags(WindowManager.LayoutParams.FLAG_SECURE) }
    }
    var key by remember { mutableStateOf("") }
    var password by remember { mutableStateOf("") }
    var confirm by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<String?>(null) }
    var busy by remember { mutableStateOf(false) }
    var result by remember { mutableStateOf<String?>(null) }
    var complete by remember { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    AlertDialog(properties = androidx.compose.ui.window.DialogProperties(securePolicy = androidx.compose.ui.window.SecureFlagPolicy.SecureOn), onDismissRequest = { if (!busy) onClose() }, title = { Text(if (enroll) "Private recovery key" else "Reset password") },
        text = { Column(Modifier.heightIn(max = 480.dp).verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(10.dp)) {
            Text(if (enroll) "Create a private one-time key while signed in. Creating a new key replaces your old key. Save it somewhere private, not in chat. It is shown once."
                else "Use the private recovery key you saved while logged in. Already locked out without a saved key? This method cannot recover your account.")
            generated?.let { Text(it, color = Gold2); Text("Write this key down privately now. It cannot be shown again. Never share it. After using it, sign in and create a new key.") }
            if (!complete && generated == null) {
                if (!enroll) OutlinedTextField(key, { key = it.trim() }, label = { Text("Private recovery key") }, visualTransformation = PasswordVisualTransformation(), singleLine = true)
                OutlinedTextField(password, { password = it }, label = { Text(if (enroll) "Current password" else "New password (8-128 characters)") }, visualTransformation = PasswordVisualTransformation(), singleLine = true)
                if (!enroll) OutlinedTextField(confirm, { confirm = it }, label = { Text("Confirm new password") }, visualTransformation = PasswordVisualTransformation(), singleLine = true)
            }
            result?.let { Text(it) }
            if (busy) LinearProgressIndicator(Modifier.fillMaxWidth())
            if (!enroll) Text("The key is one-time. If a reset times out or fails after submission, try logging in with your new password first. The key may already be used. Existing access sessions may last until their expiry. Email recovery is not configured.")
        } },
        confirmButton = {
            if (generated == null && !complete) TextButton(enabled = !busy && password.isNotBlank() && (enroll || (key.matches(Regex("[0-9a-fA-F]{64}")) && password.length in 8..128 && password == confirm)), onClick = {
                busy = true; result = null
                scope.launch {
                    try {
                        val r = recoveryRequest(if (enroll) JSONObject().put("action", "enroll").put("current_password", password)
                            else JSONObject().put("action", "redeem").put("recovery_key", key).put("new_password", password), enroll)
                        password = ""; confirm = ""; key = ""
                        if (enroll) generated = r.getString("recovery_key")
                        else { complete = true; result = "Password reset. Close this window and log in with your new password. Create a new recovery key after signing in." }
                    } catch (_: Exception) {
                        password = ""; confirm = ""; key = ""
                        result = if (enroll) "Could not create a key. Check your current password and connection. An uncertain response may have replaced an older key; create a new key before relying on it."
                            else "Could not confirm reset. Check the key or try later. If you submitted a valid key, first try logging in with your new password. Do not assume the key is still usable."
                    }
                    busy = false
                }
            }) { Text(if (enroll) "Create key" else "Reset password") }
        }, dismissButton = { TextButton(enabled = !busy, onClick = { generated = null; key = ""; password = ""; confirm = ""; onClose() }) { Text(if (generated != null) "I saved it privately" else "Close") } })
}
